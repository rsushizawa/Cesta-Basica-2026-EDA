from typing import Protocol
import numpy as np

class ClusteringModel(Protocol):
    def fit(self, X: np.ndarray) -> 'ClusteringModel': ...
    def predict(self, X: np.ndarray) -> np.ndarray: ...
    @property
    def centroids(self) -> np.ndarray: ...
    @property
    def inertia(self) -> float: ...
